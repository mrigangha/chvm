import * as fs from "node:fs"
// Embeds the runtime sources as strings, so the compiler does not read them at run time.
const src = fs.readFileSync("src/prelude.ts", "latin1")
fs.writeFileSync("src/prelude_src.ts", "// Generated by `node build_prelude.ts`. Do not edit.\nexport const PRELUDE_SRC: string = " + JSON.stringify(src) + "\n", "latin1")
const asm = fs.readFileSync("src/runtime.s", "latin1")
fs.writeFileSync("src/prelude_asm.ts", "// Generated by `node build_prelude.ts`. Do not edit.\nexport const PRELUDE_ASM: string = " + JSON.stringify(asm) + "\n", "latin1")
